export type Locale = "fr" | "en";
const DICTIONARIES: Record<Locale, Dictionary> = { fr, en };
const STORAGE_KEY = "hf-creator-locale";

function readStoredLocale(): Locale {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    return stored === "en" ? "en" : "fr";
  } catch {
    return "fr";
  }
}

let currentLocale: Locale = typeof window === "undefined" ? "fr" : readStoredLocale();
const listeners = new Set<() => void>();

export function getLocale(): Locale {
  return currentLocale;
}

export function setLocale(locale: Locale): void {
  currentLocale = locale;
  try {
    window.localStorage.setItem(STORAGE_KEY, locale);
  } catch {
    // Private mode: the choice lasts for this tab only.
  }
  document.documentElement.lang = locale;
  for (const listener of listeners) listener();
}

function subscribe(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function translate(
  locale: Locale,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  const template = DICTIONARIES[locale][key] ?? fr[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    vars[name] === undefined ? match : String(vars[name]),
  );
}

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

/** The active locale and a translator bound to it; re-renders when the locale changes. */
export function useI18n(): { locale: Locale; t: Translate } {
  const locale = useSyncExternalStore(subscribe, getLocale, () => "fr" as Locale);
  return { locale, t: (key, vars) => translate(locale, key, vars) };
}

export function formatDate(locale: Locale, iso: string): string {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return "—";
  return new Intl.DateTimeFormat(locale === "fr" ? "fr-FR" : "en-GB", {
    dateStyle: "medium",
    timeStyle: "short",
  }).format(date);
}

export function formatDuration(seconds: number | null): string {
  if (seconds === null) return "—";
  const total = Math.round(seconds);
  const minutes = Math.floor(total / 60);
  return `${minutes}:${String(total % 60).padStart(2, "0")}`;
}

export function formatBytes(locale: Locale, bytes: number): string {
  const unit = (key: MessageKey) => translate(locale, key);
  if (bytes < 1024 * 1024) return `${Math.max(1, Math.round(bytes / 1024))} ${unit("unit.kb")}`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} ${unit("unit.mb")}`;
}
